/**
 * Regenerates content/errata.yaml from the official errata articles.
 *   npm run parse-errata             # fetch the live articles
 *   npm run parse-errata -- --offline  # use test/fixtures/articles/*.json
 * Hand edits survive: a `match:` set on an entry (catalogue spelling of the name) is kept.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import YAML from 'yaml';
import { articleFromHtml, parseErrata, type Article } from './lib/articles.ts';
import { fetchText, offline } from './lib/sources.ts';

export const ERRATA_ARTICLES = [
  'https://playriftbound.com/en-us/news/rules-and-releases/riftbound-origins-card-errata/',
  'https://playriftbound.com/en-us/news/rules-and-releases/riftbound-spiritforged-errata/',
  'https://playriftbound.com/en-us/news/rules-and-releases/unleashed-errata-updates/',
  'https://playriftbound.com/en-us/news/announcements/vendetta-errata-updates/',
  'https://playriftbound.com/en-us/news/announcements/radiance-errata-updates/',
];

const FILE = join(process.cwd(), 'content/errata.yaml');
const slug = (url: string) => url.replace(/\/$/, '').split('/').pop()!;

async function loadArticle(url: string): Promise<Article> {
  if (offline) return JSON.parse(await readFile(join('test/fixtures/articles', `${slug(url)}.json`), 'utf8'));
  return articleFromHtml(await fetchText(url));
}

interface Entry { name: string; match?: string; date: string; source: string; text: string; old_text?: string }

async function main() {
  const previous = new Map<string, Entry>();
  if (existsSync(FILE)) {
    const doc = YAML.parse(await readFile(FILE, 'utf8')) as { errata?: Entry[] };
    for (const e of doc?.errata ?? []) previous.set(`${e.source}|${e.name}`, e);
  }
  const entries: Entry[] = [];
  for (const url of ERRATA_ARTICLES) {
    const article = await loadArticle(url);
    const parsed = parseErrata(article);
    if (!parsed.length) throw new Error(`${url}: no errata parsed (layout changed?)`);
    for (const p of parsed) {
      const prev = previous.get(`${url}|${p.name}`);
      entries.push({
        name: p.name,
        ...(prev?.match ? { match: prev.match } : {}),
        date: article.publishDate.slice(0, 10),
        source: url,
        text: p.text,
        old_text: p.old_text,
      });
    }
    console.log(`${slug(url)}: ${parsed.length}`);
  }
  const header = [
    '# Official card errata, one entry per card per article.',
    '# Generated by `npm run parse-errata` from the articles below, then hand-editable:',
    '#   name   – as printed in the article',
    '#   match  – optional: catalogue spelling when `name` does not resolve to a card (kept on regenerate)',
    '#   date   – article publish date; the latest entry for a card wins',
    '#   text   – the new Oracle text, verbatim ([C] [1] [E] [M] [A] symbols as in the article)',
    '',
  ].join('\n');
  await writeFile(FILE, header + YAML.stringify({ errata: entries }, { lineWidth: 0 }));
  console.log(`wrote ${entries.length} errata to content/errata.yaml`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
